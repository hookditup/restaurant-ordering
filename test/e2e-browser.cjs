// Full browser run: order on the website, then work it on the kitchen screen.
const { chromium } = require('playwright');
const http = require('http'), fs = require('fs'), path = require('path');
const [root, shots] = process.argv.slice(2);
const types = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.webp': 'image/webp', '.png': 'image/png', '.mp4': 'video/mp4' };
const srv = http.createServer((q, r) => {
  let f = path.join(root, decodeURIComponent(q.url.split('?')[0]));
  if (fs.existsSync(f) && fs.statSync(f).isDirectory()) f = path.join(f, 'index.html');
  if (!fs.existsSync(f)) { r.writeHead(404); return r.end('nf'); }
  r.writeHead(200, { 'content-type': types[path.extname(f)] || 'text/plain' }); fs.createReadStream(f).pipe(r);
});
(async () => {
  await new Promise((s) => srv.listen(8130, s));
  const B = 'http://localhost:8130';
  const br = await chromium.launch();
  const errors = [];
  const watch = (p) => { p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => { if (m.type() === 'error' && !/fonts|maps|Failed to load resource/.test(m.text())) errors.push(m.text()); }); };
  const route = async (ctx) => {
    await ctx.route(/google\.com\/maps|fonts\.g/, (r) => r.abort());
    await ctx.route(/supabase\.co/, async (r) => {
      if (r.request().method() === 'OPTIONS') return r.fulfill({ status: 200, headers: { 'access-control-allow-origin': '*', 'access-control-allow-headers': '*', 'access-control-allow-methods': '*' } });
      const res = await fetch(r.request().url(), { method: r.request().method(), headers: { ...(r.request().headers()), host: undefined }, body: r.request().postData() ?? undefined });
      r.fulfill({ status: res.status, body: await res.text(), headers: { 'content-type': 'application/json', 'access-control-allow-origin': '*' } });
    });
  };
  const m = await br.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await route(m);
  const p = await m.newPage(); watch(p);
  await p.goto(`${B}/menu/`);
  await p.waitForSelector('#ro-time', { timeout: 20000 });
  const pickFor = (min, max) => p.$$eval('#ro-time option', (os, [a, b]) => { const o = os.find((x) => { const d = new Date(x.value); const v = d.toLocaleTimeString('en-US', { timeZone: 'America/Denver', hour12: false, hour: '2-digit', minute: '2-digit' }).split(':'); const n = +v[0] * 60 + +v[1]; return n >= a && n < b; }); return o && o.value; }, [min, max]);
  const lunchSlot = await pickFor(11 * 60, 13 * 60), dinnerSlot = await pickFor(17 * 60, 20 * 60);
  await p.selectOption('#ro-time', lunchSlot);
  await p.waitForTimeout(300);
  const secs = await p.$$eval('.ro-cat h2', (h) => h.map((x) => x.textContent));
  await p.screenshot({ path: `${shots}/1-menu.jpg`, type: 'jpeg', quality: 60 });
  const lunchPrice = await p.$eval('.ro-cat:has(h2:text-is("Traditional Dishes")) .ro-item:has(strong:text-is("Tacos")) b', (e) => e.textContent);
  await p.selectOption('#ro-time', dinnerSlot); await p.waitForTimeout(300);
  const dinnerPrice = await p.$eval('.ro-cat:has(h2:text-is("Traditional Dishes")) .ro-item:has(strong:text-is("Tacos")) b', (e) => e.textContent);
  const dinnerSecs = await p.$$eval('.ro-cat h2', (h) => h.length);
  await p.selectOption('#ro-time', dinnerSlot);
  await p.click('.ro-cat:has(h2:text-is("Traditional Dishes")) .ro-item:has(strong:text-is("Tacos"))');
  await p.waitForSelector('.ro-dialog[open]');
  await p.click('.ro-add');
  const need = await p.textContent('.ro-dialog .ro-err');
  await p.click('.ro-opt:has(span:text-is("Steak"))');
  await p.click('.ro-opt:has(span:text-is("Fries"))');
  await p.click('.ro-opt:has(span:text-is("No Onion"))');
  await p.fill('#ro-note', 'Extra lime please');
  await p.click('[data-q="1"]');
  const noteKept = await p.inputValue('#ro-note');
  const btn = await p.textContent('.ro-add');
  await p.screenshot({ path: `${shots}/2-item.jpg`, type: 'jpeg', quality: 60, fullPage: false });
  await p.click('.ro-add');
  await p.click('.ro-item:has(strong:text-is("Guacamole"))'); await p.waitForSelector('.ro-dialog[open]'); await p.click('.ro-add');
  await p.click('#ro-open');
  await p.waitForSelector('#ro-sum .ro-total');
  await p.fill('[name=first_name]', 'Test'); await p.fill('[name=last_name]', 'Guest'); await p.fill('[name=phone]', '435-555-0100'); await p.fill('[name=email]', 'test@example.com');
  await p.click('[data-tip="18"]');
  await p.waitForFunction(() => /Tip/.test(document.querySelector('#ro-sum')?.textContent || ''));
  const first = await p.inputValue('[name=first_name]');
  const sum = await p.textContent('#ro-sum');
  await p.screenshot({ path: `${shots}/3-cart.jpg`, type: 'jpeg', quality: 60 });
  await p.click('#ro-pay .ro-add');
  await p.waitForURL(/\/order\//, { timeout: 20000 });
  await p.waitForSelector('#ro-status h1:not(:empty)'); await p.waitForTimeout(1200);
  const status = await p.textContent('#ro-status');
  await p.screenshot({ path: `${shots}/4-status.jpg`, type: 'jpeg', quality: 60 });
  const k = await br.newContext({ viewport: { width: 1180, height: 820 } }); await route(k);
  const q = await k.newPage(); watch(q);
  await q.goto(`${B}/kitchen/`);
  await q.fill('[name=email]', process.env.STAFF_EMAIL); await q.fill('[name=password]', process.env.STAFF_PASSWORD); await q.click('.k-login button');
  await q.waitForSelector('.k-card');
  const kc = await q.textContent('.k-new');
  await q.screenshot({ path: `${shots}/5-kitchen.jpg`, type: 'jpeg', quality: 60 });
  await q.click('.k-new [data-move=accept]'); await q.waitForSelector('.k-accepted');
  await q.click('.k-accepted [data-move=ready]'); await q.waitForSelector('.k-ready');
  await p.reload(); await p.waitForTimeout(1500);
  const after = await p.textContent('#ro-status strong');
  await q.click('.k-ready [data-move=complete]'); await q.waitForTimeout(1000);
  const left = await q.$$eval('.k-card', (c) => c.length);
  const ov = await p.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  console.log(JSON.stringify({ secs, dinnerSecs, lunchPrice, dinnerPrice, need, noteKept, btn, first, sum, status: status.slice(0, 260), kc: kc.slice(0, 260), after, left, ov, errors }, null, 1));
  await br.close(); srv.close();
})().catch((e) => { console.error(e); process.exit(1); });
